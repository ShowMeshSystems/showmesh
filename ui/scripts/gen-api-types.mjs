#!/usr/bin/env node
// Generates ui/src/api/generated/schema.d.ts from api/openapi.yaml.
//
// This is what makes ADR-015's "generated from or verified against the Go
// types" real: api/openapi.yaml is already conformance-tested against real
// coordinator handler responses (Step 3), so a TypeScript type generated
// from it is transitively verified against the Go types without this
// script having to know anything about Go.
//
// Two properties this script is written to guarantee, both load-bearing
// for CI's regenerate-and-diff check (Makefile's ui-gen-check):
//   1. It works with the repository checked out anywhere — the spec path
//      is resolved relative to this file, never to process.cwd() or a
//      hardcoded absolute path.
//   2. It requires no network access — openapi-typescript is pointed at
//      the local file directly, and api/openapi.yaml contains no external
//      $ref (verified by reading it; every $ref in that document is an
//      internal `#/components/...` pointer).
import { fileURLToPath } from 'node:url'
import path from 'node:path'
import fs from 'node:fs/promises'
import openapiTS, { astToString } from 'openapi-typescript'

const scriptDir = path.dirname(fileURLToPath(import.meta.url))
const uiRoot = path.resolve(scriptDir, '..')
const specPath = path.resolve(uiRoot, '..', 'api', 'openapi.yaml')
const outPath = path.resolve(uiRoot, 'src', 'api', 'generated', 'schema.d.ts')

const banner = `/**
 * GENERATED FILE. Do not hand-edit.
 *
 * Generated by ui/scripts/gen-api-types.mjs from api/openapi.yaml, which is
 * itself conformance-tested against real coordinator handler responses
 * (ADR-014, ADR-015, ADR-020). Regenerate with \`npm run gen:api\` after any
 * change to the OpenAPI document; CI regenerates and fails the build on any
 * diff (see Makefile target ui-gen-check), so a hand-edit here would be
 * silently overwritten and would not be honest about the contract anyway.
 */
`

async function main() {
  const ast = await openapiTS(new URL(`file://${specPath}`), {
    // No remote refs are expected (see the file-level comment above); this
    // is not a network-access opt-out, it's a guard so a future accidental
    // external $ref fails loudly here instead of degrading to a silent
    // network dependency in CI.
    fetch: () => {
      throw new Error(
        'gen-api-types: unexpected network fetch — api/openapi.yaml must not reference remote schemas',
      )
    },
  })
  const output = banner + astToString(ast)

  await fs.mkdir(path.dirname(outPath), { recursive: true })
  await fs.writeFile(outPath, output, 'utf8')
  console.log(`wrote ${path.relative(uiRoot, outPath)}`)
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
